"""
Idealized IMU interface backed by the simulation's World (see sim/sim_design.md) instead of hardware.

Follows the IMU contract like LSM6DSV320X does:
- FIFO of grouped (timestamp, accel, gyro) samples, WORDS_PER_SAMPLE words each. When it overflows, the oldest
  samples are lost. Samples are generated by the World on demand, at the IMU's own sample times, so nothing runs
  in the background.
- Raw COUNTER_BITS ticks of nominal TICK_NS, starting from a random tick and running (1 + clock rate error) fast,
  like a real oscillator. This exercises clamour's SensorClockMapper.
- Accel in mg (specific force: +1000 mg on z at rest) and gyro in mdps, NOT bias-corrected.
- get_attitude(): yaw relative to the start heading, pitch = roll = 0 (flat 2D world), like the SFLP game vector.
- Noise densities come from the World, so clamour's noise models match the simulated noise exactly.
- Scale factor matrices are stored but not applied: an ideal sensor has no scale error to correct.

The World works in SI units; this class converts to clamour's mg / mdps / deg.
"""
import time

import numpy as np

from .imu import IMU, RawIMUSample
from .simulation_tag import connect_world

TICK_NS = 21_700         # Nominal tick, same as the LSM6DSV320X
COUNTER_BITS = 32
FIFO_CAPACITY_WORDS = 256
WORDS_PER_SAMPLE = 3     # Timestamp, accel and gyro words
MG = 9.80665 / 1000      # m/s^2 per mg
MDPS = np.pi / 180_000   # rad/s per mdps

class SimulatedIMU(IMU):
    """
    ARGS:
        - tag_id: ID of the tag carrying this IMU, as known by the World
        - world_address: address of the World server (sim/world_server.py)
    Build it inside the process that reads it (clamour's create_imu does), since it connects to the World right away.
    """
    def __init__(self, tag_id: int, world_address):
        self._tag_id = tag_id
        self._world = connect_world(world_address)
        spec = self._world.imu_spec(tag_id)
        self._sample_rate_hz = spec['sample_rate_hz']
        self._accel_density_mg = spec['accel_noise_density'] / MG
        self._gyro_density_mdps = spec['gyro_noise_density'] / MDPS
        self._clock_rate = 1.0 + spec['clock_rate_error']
        self._start_tick = spec['start_tick']
        self._start_time = time.monotonic()
        # Sample k is taken at start_time + k * period (true time). The oscillator sets both the sample rate and
        # the ticks, so a fast clock samples early but still stamps samples a nominal number of ticks apart.
        self._period = 1.0 / (self._sample_rate_hz * self._clock_rate)
        self._ticks_per_sample = 1e9 / (self._sample_rate_hz * TICK_NS)
        self._next_sample = 1  # Index of the oldest sample not read yet
        self._accel_scale_factor_mg = np.eye(3)
        self._gyro_scale_factor_mdps = np.eye(3)

    ### ACCEL/GYRO SCALE FACTOR (stored only: an ideal sensor has no scale error)
    @property
    def accel_scale_factor_mg(self) -> np.ndarray:
        return self._accel_scale_factor_mg

    @accel_scale_factor_mg.setter
    def accel_scale_factor_mg(self, value: np.ndarray) -> None:
        self._accel_scale_factor_mg = np.array(value, dtype=float).reshape(3, 3)

    @property
    def gyro_scale_factor_mdps(self) -> np.ndarray:
        return self._gyro_scale_factor_mdps

    @gyro_scale_factor_mdps.setter
    def gyro_scale_factor_mdps(self, value: np.ndarray) -> None:
        self._gyro_scale_factor_mdps = np.array(value, dtype=float).reshape(3, 3)

    ### SENSOR CONSTANTS
    @property
    def accel_covar_density_mg(self) -> float:
        return self._accel_density_mg**2

    @property
    def gyro_covar_density_mg(self) -> float:
        return self._gyro_density_mdps**2

    @property
    def timestamp_tick_ns(self) -> float:
        return TICK_NS

    @property
    def timestamp_counter_bits(self) -> int:
        return COUNTER_BITS

    @property
    def sample_rate_hz(self) -> float:
        return self._sample_rate_hz

    @property
    def fifo_capacity_words(self) -> int:
        return FIFO_CAPACITY_WORDS

    ### FIFO
    def _pending_samples(self) -> int:
        """Samples taken but not read yet. Drops the oldest ones the FIFO couldn't hold."""
        taken = int((time.monotonic() - self._start_time) / self._period)
        self._next_sample = max(self._next_sample, taken - FIFO_CAPACITY_WORDS // WORDS_PER_SAMPLE + 1)
        return taken - self._next_sample + 1

    def get_FIFO_count(self) -> int:
        return self._pending_samples() * WORDS_PER_SAMPLE

    def read_FIFO(self, apply_bias: bool = False, word_count: int | None = None) -> list[RawIMUSample]:
        if apply_bias:
            raise ValueError("SimulatedIMU only provides raw samples: the factor graph handles the bias")
        n_samples = self._pending_samples()
        if word_count is not None:
            n_samples = min(n_samples, word_count // WORDS_PER_SAMPLE)
        if n_samples <= 0:
            return []
        indices = np.arange(self._next_sample, self._next_sample + n_samples)
        self._next_sample += n_samples
        accel, gyro = self._world.imu_samples(self._tag_id, (self._start_time + indices * self._period).tolist())
        ticks = (self._start_tick + np.round(indices * self._ticks_per_sample).astype(np.int64)) % (1 << COUNTER_BITS)
        return [(int(tick), a / MG, g / MDPS) for tick, a, g in zip(ticks, accel, gyro)]

    def discard_FIFO(self) -> None:
        self._next_sample = int((time.monotonic() - self._start_time) / self._period) + 1

    ### CLOCK AND ATTITUDE
    def get_timestamp(self) -> int:
        elapsed_ns = (time.monotonic() - self._start_time) * 1e9
        return int(self._start_tick + elapsed_ns * self._clock_rate / TICK_NS) % (1 << COUNTER_BITS)

    def get_attitude(self) -> tuple[float, float, float]:
        yaw = np.rad2deg(self._world.imu_attitude(self._tag_id, time.monotonic()))
        return float(yaw), 0.0, 0.0

    def close(self) -> None:
        pass
